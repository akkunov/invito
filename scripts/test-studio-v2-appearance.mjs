import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,createEditorSession,dispatchStudioCommand,beginStudioTransaction,commitStudioTransaction,cancelStudioTransaction,undoStudio,redoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {uniformCorners,radiusCss,appearanceCss,maskCss,contentTransform} from "../src/features/studio-v2/core/appearance.ts";
let doc=createEmptyProjectV2("appearance-test");
const root=doc.nodes["frame-1"];
const shape={id:"shape-a",parentId:"frame-1",type:"shape",x:20,y:30,width:100,height:80,rotation:0,opacity:1,visible:true,locked:false,shape:"rectangle",fill:"#FF0000",stroke:null,strokeWidth:0};
doc=applyStudioCommand(doc,{kind:"insertNode",parentId:"frame-1",node:shape});
const visual={corners:{topLeft:10,topRight:20,bottomRight:30,bottomLeft:40},fill:{kind:"linear",angle:90,stops:[{color:"#FFFFFF",position:0},{color:"#000000",position:100}]},stroke:{color:"#123456",width:2,style:"dotted"},shadow:{color:"#000000",x:0,y:8,blur:20,spread:0,opacity:.5},flipX:true,mask:"diamond"};
let s=createEditorSession(doc);
s=dispatchStudioCommand(s,{kind:"updateNode",id:"shape-a",changes:{visual}});
assert.equal(radiusCss(s.document.nodes["shape-a"]),"10px 20px 30px 40px");
assert.equal(appearanceCss(s.document.nodes["shape-a"]).background,"linear-gradient(90deg, #FFFFFF 0%, #000000 100%)");
assert.equal(appearanceCss(s.document.nodes["shape-a"]).outline,"2px dotted #123456");
assert.equal(appearanceCss(s.document.nodes["shape-a"]).boxShadow,"0px 8px 20px 0px #00000080");
assert.ok(maskCss(s.document.nodes["shape-a"]).startsWith("polygon"));
assert.equal(contentTransform(s.document.nodes["shape-a"]),"scale(-1, 1)");
assert.deepEqual(uniformCorners(12),{topLeft:12,topRight:12,bottomRight:12,bottomLeft:12});
assert.deepEqual(parseProjectV2(JSON.parse(JSON.stringify(s.document))),s.document);
assert.equal(undoStudio(s).document.nodes["shape-a"].visual,undefined);
assert.throws(()=>applyStudioCommand(doc,{kind:"updateNode",id:"shape-a",changes:{visual:{corners:uniformCorners(-1)}}}));
s=dispatchStudioCommand(s,{kind:"setLayerState",id:"shape-a",locked:true,visible:false});
assert.equal(s.document.nodes["shape-a"].locked,true);
assert.throws(()=>dispatchStudioCommand(s,{kind:"updateNode",id:"shape-a",changes:{x:20}}));
s=dispatchStudioCommand(s,{kind:"setLayerState",id:"shape-a",locked:false,visible:true});
assert.equal(s.document.nodes["shape-a"].visible,true);
s=dispatchStudioCommand(s,{kind:"createPage",page:{id:"page-two",name:"Вторая",rootNodeId:"frame-two",placement:{x:1600,y:0}},root:{...root,id:"frame-two",children:[]}});
s=dispatchStudioCommand(s,{kind:"insertNode",parentId:"frame-two",node:{...shape,id:"shape-b",parentId:"frame-two"}});
s=dispatchStudioCommand(s,{kind:"setResponsiveOverride",id:"shape-b",device:"mobile",patch:{x:42}});
const original=s.document;
s=dispatchStudioCommand(s,{kind:"reorderPage",id:"page-two",index:0});
assert.equal(s.document.pages[0].id,"page-two");
assert.equal(undoStudio(s).document.pages[0].id,"page-1");
s=beginStudioTransaction(s,"move page");
s=dispatchStudioCommand(s,{kind:"movePage",id:"page-two",placement:{x:1800,y:100}});
s=dispatchStudioCommand(s,{kind:"movePage",id:"page-two",placement:{x:2000,y:200}});
s=commitStudioTransaction(s);
assert.equal(s.document.pages[0].placement.x,2000);
assert.equal(undoStudio(s).document.pages[0].placement.x,1600);
let cancelled=beginStudioTransaction(s,"cancel");
cancelled=dispatchStudioCommand(cancelled,{kind:"movePage",id:"page-two",placement:{x:999,y:0}});
assert.equal(cancelStudioTransaction(cancelled).document.pages[0].placement.x,2000);
const beforeDelete=s.document;
s=dispatchStudioCommand(s,{kind:"deletePage",id:"page-two"});
assert.equal(s.document.pages.length,1);
assert.equal(s.document.nodes["shape-b"],undefined);
assert.equal(s.document.responsiveOverrides.mobile["shape-b"],undefined);
assert.throws(()=>dispatchStudioCommand(s,{kind:"deletePage",id:"page-1"}));
s=undoStudio(s);
assert.deepEqual(s.document.pages,beforeDelete.pages);
assert.deepEqual(s.document.nodes,beforeDelete.nodes);
assert.deepEqual(s.document.responsiveOverrides,original.responsiveOverrides);
assert.equal(redoStudio(s).document.nodes["shape-b"],undefined);
console.log("PASS: appearance, independent corners, layer lock, page order/move/delete, cancel, undo and redo");
