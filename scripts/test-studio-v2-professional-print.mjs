import assert from "node:assert/strict";
import {professionalGeometry,professionalPrintSource} from "../src/features/studio-v2/core/professional-print.ts";
import {validatePrintSource,validateCmykProfile,pdfxDefinition} from "./print-professional.mjs";
const g=professionalGeometry(1080,1920,111,3);
assert.equal(g.trimWidthMm,105);
assert.equal(g.heightMm,111*1920/1080);
assert.equal(g.trimHeightMm,g.heightMm-6);
assert.throws(()=>professionalGeometry(1080,1920,20,10));
assert.throws(()=>professionalGeometry(1,1,100,-1));
const source=professionalPrintSource({markup:'<div style="width:1080px;height:1920px;background:#eee">INVITO</div>',width:1080,height:1920},111,3,'Wedding <&>');
assert.deepEqual(validatePrintSource(JSON.parse(JSON.stringify(source))),source);
assert.match(source.html,/@page\{size:111mm /);
assert.match(source.html,/Wedding &lt;&amp;&gt;/);
assert.ok(source.html.includes("default-src 'none'"));
assert.throws(()=>validatePrintSource({...source,geometry:{...g,trimWidthMm:108}}));
const icc=Buffer.alloc(128);icc.writeUInt32BE(128);icc.write("prtr",12);icc.write("CMYK",16);icc.write("acsp",36);
validateCmykProfile(icc);
assert.throws(()=>validateCmykProfile(Buffer.alloc(128)));
const rgb=Buffer.from(icc);rgb.write("RGB ",16);assert.throws(()=>validateCmykProfile(rgb));
const ps=pdfxDefinition("/tmp/test(ICC).icc","FOGRA test (name)",3);
assert.match(ps,/\/GTS_PDFXVersion \(PDF\/X-4\)/);
assert.match(ps,/\/N 4/);
assert.ok(ps.includes(Buffer.from("/tmp/test(ICC).icc").toString("hex")));
assert.ok(ps.includes(Buffer.from("FOGRA test (name)").toString("hex")));
assert.ok(ps.includes("/PDFXTrimBoxToMediaBoxOffset [8.50393701 8.50393701 8.50393701 8.50393701]"));
console.log("PASS: professional print geometry, source pack, CMYK ICC header and PDF/X trim intent");
