import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,dispatchStudioCommand,createEditorSession,undoStudio,redoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {responsiveDocument,responsiveSource,presentationSize} from "../src/features/studio-v2/core/responsive-engine.ts";
import {deviceGesture,devicePatch,canDragDeviceNode,canResizeDeviceNode} from "../src/features/studio-v2/core/responsive-editing.ts";
import {resolveStyleDocument} from "../src/features/studio-v2/core/style-tokens.ts";
let doc=createEmptyProjectV2("responsive-pro");
const shape={id:"box",parentId:"frame-1",type:"shape",x:100,y:200,width:200,height:100,rotation:0,opacity:1,visible:true,locked:false,shape:"rectangle",fill:"#FF0000",stroke:null,strokeWidth:0,anchors:{x:"end",y:"start"}};
const text={id:"title",parentId:"frame-1",type:"text",x:20,y:400,width:300,height:100,rotation:0,opacity:1,visible:true,locked:false,runs:[{text:"Кыргызча",style:{fontFamily:"sans",fontSize:42,fontWeight:400,italic:false,underline:false,strike:false,color:"#000000"}}],textAlign:"center",bindingKey:null};
const cmd=c=>{doc=applyStudioCommand(doc,c);};
cmd({kind:"insertNode",parentId:"frame-1",node:shape});cmd({kind:"insertNode",parentId:"frame-1",node:text});
cmd({kind:"setPageProfile",id:"page-1",device:"mobile",profile:{width:900,height:1400,mode:"reflow"}});
let solved=responsiveDocument(doc,"mobile");
assert.equal(solved.nodes.box.x,-80);
assert.equal(canDragDeviceNode(solved,"box"),true);
assert.equal(canResizeDeviceNode(solved,"box"),false);
let session=createEditorSession(doc);
session=dispatchStudioCommand(session,deviceGesture(doc,solved,"box","mobile",{x:40,y:30}));
assert.equal(session.document.responsiveOverrides.mobile.box.x,140);
assert.equal(responsiveDocument(session.document,"mobile").nodes.box.x,-40);
assert.equal(responsiveDocument(session.document,"desktop").nodes.box.x,100);
assert.equal(session.document.nodes.box.x,100);
assert.equal(undoStudio(session).document.responsiveOverrides,undefined);
doc=redoStudio(undoStudio(session)).document;
cmd({kind:"updateNode",id:"box",changes:{anchors:{x:"start",y:"start"}}});
solved=responsiveDocument(doc,"mobile");
assert.equal(canResizeDeviceNode(solved,"box"),true);
cmd(deviceGesture(doc,solved,"box","mobile",{x:50,y:20},"se"));
assert.equal(responsiveDocument(doc,"mobile").nodes.box.width,250);
assert.equal(responsiveDocument(doc,"desktop").nodes.box.width,200);
cmd({kind:"putStyleToken",token:{id:"type",name:"Heading",kind:"typography",value:{fontFamily:"serif",fontSize:80,fontWeight:600,lineHeight:1.2,letterSpacing:2}}});
cmd({kind:"bindStyle",id:"title",slot:"typography",tokenId:"type"});
cmd(devicePatch(doc,"title","mobile",{textStyle:{fontSize:24,lineHeight:1.6,textAlign:"left"}}));
let styled=resolveStyleDocument(doc);
assert.equal(responsiveDocument(styled,"mobile").nodes.title.runs[0].style.fontSize,24);
assert.equal(responsiveDocument(styled,"tablet").nodes.title.runs[0].style.fontSize,80);
assert.equal(responsiveDocument(styled,"mobile").nodes.title.runs[0].text,"Кыргызча");
assert.equal(responsiveDocument(styled,"mobile").nodes.title.lineHeight,1.6);
cmd(devicePatch(doc,"title","mobile",{textStyle:{fontSize:undefined,lineHeight:undefined,textAlign:undefined}}));
assert.equal(doc.responsiveOverrides.mobile.title,undefined);
assert.equal(responsiveDocument(resolveStyleDocument(doc),"mobile").nodes.title.runs[0].style.fontSize,80);
cmd(devicePatch(doc,"frame-1","mobile",{frameLayout:{layout:"vertical",gap:35,padding:{top:10,left:20,right:20,bottom:10}}}));
solved=responsiveDocument(doc,"mobile");
assert.equal(solved.nodes.box.x,20);
assert.equal(solved.nodes.title.y,10+solved.nodes.box.height+35);
assert.equal(canDragDeviceNode(solved,"box"),false);
assert.equal(responsiveDocument(doc,"desktop").nodes["frame-1"].layout,"free");
assert.throws(()=>deviceGesture(doc,solved,"box","mobile",{x:20,y:20}));
cmd(devicePatch(doc,"box","mobile",{visible:false}));
assert.equal(responsiveDocument(doc,"mobile").nodes.title.y,10);
assert.equal(responsiveDocument(doc,"desktop").nodes.box.visible,true);
assert.throws(()=>applyStudioCommand(doc,devicePatch(doc,"box","tablet",{textStyle:{fontSize:20}})));
assert.throws(()=>applyStudioCommand(doc,devicePatch(doc,"title","tablet",{frameLayout:{gap:12}})));
assert.throws(()=>applyStudioCommand(doc,devicePatch(doc,"frame-1","tablet",{x:10})));
cmd({kind:"setResponsiveOverride",id:"frame-1",device:"mobile",patch:null});
assert.equal(responsiveDocument(doc,"mobile").nodes["frame-1"].layout,"free");
assert.deepEqual(parseProjectV2(JSON.parse(JSON.stringify(doc))),doc);
console.log("PASS: responsive drag, resize, anchor compensation, typography precedence, root reflow/layout, visibility, validation and undo");
