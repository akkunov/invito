import { readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import assert from "node:assert/strict";
const root=resolve(import.meta.dirname,"..");
const read=(p)=>readFileSync(resolve(root,p),"utf8");
const config=read("src/features/invitations/collection-templates.ts");
const covers=read("src/features/invitations/heritage-covers.ts");
const registry=read("src/features/invitations/seed-templates.ts");
const picker=read("src/components/editor/heritage-cover-picker.tsx");
const canvas=read("src/components/invitation/invitation-canvas.tsx");
const source=read("src/features/invitations/use-invitation-editor.ts");
const coverIds=[...covers.matchAll(/"id": "(heritage-[a-z-]+)"/g)].map(m=>m[1]);
assert.equal(coverIds.length,10,"10 national covers");
assert.equal(new Set(coverIds).size,10,"national IDs unique");
for(const id of coverIds)assert.ok(existsSync(resolve(root,`public/images/heritage/${id.slice(9)}.webp`)),id);
const templates=[...config.matchAll(/"id": "(collection-[a-z-]+)"/g)].map(m=>m[1]);
assert.equal(templates.length,20,"10 full designs plus 10 heritage templates");
assert.equal(new Set(templates).size,20);
assert.match(registry,/\.\.\.collectionTemplates/);
assert.match(canvas,/visibleDocument/);
assert.match(canvas,/HeritageCover/);
assert.match(picker,/aria-pressed/);
assert.match(source,/updateCoverStyle/);
assert.match(source,/coverStyleId: document\.media\?\.coverStyleId/);
assert.match(read("src/app/collection.css"),/prefers-reduced-motion/);
console.log("PASS 10 invitation designs + 10 standalone heritage covers; editor persistence and rendering wired");
