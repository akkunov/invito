import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,applyStudioBatch,createEditorSession,dispatchStudioCommand,undoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {snapshotVariant,instantiateComponent,imageNode} from "../src/features/studio-v2/core/component-engine.ts";
import {detectImage,boundedSize,safeSvgAttribute,validateSvgSource,SVG_ELEMENTS} from "../src/features/studio-v2/core/media-policy.ts";
assert.equal(detectImage(Uint8Array.of(137,80,78,71,13,10,26,10)),"image/png");
assert.equal(detectImage(new TextEncoder().encode("<html>bad</html>")),null);
assert.equal(detectImage(new TextEncoder().encode('<svg xmlns="http://www.w3.org/2000/svg"></svg>')),"image/svg+xml");
assert.equal(SVG_ELEMENTS.has("script"),false);
assert.equal(SVG_ELEMENTS.has("foreignObject"),false);
assert.equal(safeSvgAttribute("onload","alert(1)"),false);
assert.equal(safeSvgAttribute("fill","url(https://example.com/a)"),false);
assert.equal(safeSvgAttribute("fill","#AA0000"),true);
assert.throws(()=>validateSvgSource("<!DOCTYPE svg [<!ENTITY x SYSTEM 'file:///etc/passwd'>]>"));
assert.deepEqual(boundedSize(6000,3000),{width:4096,height:2048});
assert.throws(()=>boundedSize(100000,100000));
let doc=createEmptyProjectV2("test-assets");
const asset={id:"asset-a",name:"Фото",mimeType:"image/png",storageKey:"local:asset-a",sizeBytes:100,pixelWidth:800,pixelHeight:400,folder:"Wedding"};
doc=applyStudioCommand(doc,{kind:"putAsset",asset});
const image=imageNode(asset,"frame-1","photo");
assert.equal(image.height,200);
doc=applyStudioCommand(doc,{kind:"insertNode",parentId:"frame-1",node:image});
assert.throws(()=>applyStudioCommand(doc,{kind:"deleteAsset",id:asset.id}));
assert.throws(()=>applyStudioCommand(doc,{kind:"putAsset",asset:{...asset,storageKey:"data:image/png;base64,abc"}}));
const variant=snapshotVariant(doc,"photo","default","Default");
const component={id:"component-a",name:"Picture",variants:[variant]};
doc=applyStudioCommand(doc,{kind:"putComponent",component});
let i=0;
let session=createEditorSession(doc);
session=dispatchStudioCommand(session,instantiateComponent(component,"default","frame-1",()=>"copy-"+(++i)));
assert.equal(session.document.nodes["copy-1"].componentRef.componentId,component.id);
assert.equal(session.document.nodes["copy-1"].assetId,asset.id);
assert.equal(session.undoStack.length,1);
assert.throws(()=>applyStudioCommand(session.document,{kind:"deleteComponent",id:component.id}));
assert.deepEqual(undoStudio(session).document.nodes,doc.nodes);
assert.deepEqual(parseProjectV2(JSON.parse(JSON.stringify(session.document))),session.document);
session=dispatchStudioCommand(session,{kind:"updateNode",id:"copy-1",changes:{focalX:.25}});
assert.equal(session.document.nodes.photo.focalX,.5);
assert.equal(session.document.components[component.id].variants[0].nodes.photo.focalX,.5);
console.log("PASS: asset references, media policy, component variants, detached overrides and undo");
