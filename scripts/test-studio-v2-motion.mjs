import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,applyStudioBatch,createEditorSession,dispatchStudioCommand,undoStudio,redoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {defaultMotion,motionSchema} from "../src/features/studio-v2/core/motion.schema.ts";
import {motionFrames,motionTracks,timelineLength,trackProgress,scrollProgress,parallaxOffset,staggerCommands,motionForPreset} from "../src/features/studio-v2/core/motion-engine.ts";
import {snapshotVariant,instantiateComponent} from "../src/features/studio-v2/core/component-engine.ts";
import {responsiveDocument} from "../src/features/studio-v2/core/responsive-engine.ts";
let doc=createEmptyProjectV2("motion-test");
const shape={id:"a",parentId:"frame-1",type:"shape",x:20,y:30,width:100,height:80,rotation:30,opacity:.65,visible:true,locked:false,shape:"rectangle",fill:"#263329",stroke:null,strokeWidth:0};
for(const id of ["a","b","c"])doc=applyStudioCommand(doc,{kind:"insertNode",parentId:"frame-1",node:{...shape,id}});
assert.equal(motionTracks(doc).length,0);
assert.equal(motionSchema.safeParse({...defaultMotion,duration:99}).success,false);
assert.equal(motionSchema.safeParse({...defaultMotion,trigger:"scroll"}).success,false);
assert.equal(motionSchema.safeParse({...defaultMotion,preset:"parallax"}).success,false);
assert.equal(motionSchema.safeParse({...defaultMotion,code:"alert(1)"}).success,false);
let session=createEditorSession(doc);
session=dispatchStudioCommand(session,staggerCommands(doc,["a","b","c"],180,100));
assert.equal(session.undoStack.length,1);
assert.deepEqual(["a","b","c"].map(id=>session.document.nodes[id].motion.delay),[100,280,460]);
assert.equal(motionTracks(undoStudio(session).document).length,0);
session=redoStudio(undoStudio(session));doc=session.document;
assert.equal(timelineLength(motionTracks(doc)),1160);
assert.equal(trackProgress(doc.nodes.a.motion,0),0);
assert.equal(trackProgress(doc.nodes.a.motion,450),.5);
assert.equal(trackProgress(doc.nodes.a.motion,10000),1);
assert.equal(scrollProgress(800,400,800),0);
assert.equal(scrollProgress(-400,400,800),1);
assert.equal(scrollProgress(200,400,800),.5);
assert.equal(parallaxOffset(motionForPreset("parallax"),0),-48);
assert.equal(parallaxOffset(motionForPreset("parallax"),1),48);
assert.equal(motionForPreset("fade",motionForPreset("parallax")).trigger,"viewport");
const a=motionTracks(doc).find(t=>t.id==="a");
assert.deepEqual(motionFrames(a),[{opacity:0,translate:"0px 48px"},{opacity:.65,translate:"0px 0px"}]);
assert.equal(doc.nodes.a.rotation,30);
assert.equal(doc.nodes.a.opacity,.65);
assert.deepEqual(motionFrames({...a,spec:{...a.spec,preset:"reveal"},canReveal:false}),[{opacity:0},{opacity:.65}]);
assert.throws(()=>staggerCommands(doc,["a","b"],3000,19000));
doc=applyStudioCommand(doc,{kind:"setLayerState",id:"c",visible:false});
assert.equal(motionTracks(doc).length,2);
const component={id:"component-motion",name:"Animated shape",variants:[snapshotVariant(doc,"a","base","Base")]};
doc=applyStudioCommand(doc,{kind:"putComponent",component});
let i=0;doc=applyStudioBatch(doc,instantiateComponent(component,"base","frame-1",()=>"instance-"+(++i)));
assert.equal(doc.nodes["instance-1"].motion.delay,100);
doc=applyStudioCommand(doc,{kind:"updateNode",id:"instance-1",changes:{motion:{...defaultMotion,preset:"fade"}}});
assert.ok(doc.nodes["instance-1"].componentOverrides.includes("motion"));
assert.equal(responsiveDocument(doc,"mobile").nodes.a.motion.delay,100);
assert.deepEqual(parseProjectV2(JSON.parse(JSON.stringify(doc))),doc);
console.log("PASS: motion schema, stagger, timeline, transform preservation, parallax, component overrides and undo/redo");
