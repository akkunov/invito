import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,createEditorSession,dispatchStudioCommand,beginStudioTransaction,commitStudioTransaction,cancelStudioTransaction,undoStudio,redoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {plainText,formatRange,replaceRange,reconcileText,normalizeRuns,sanitizePlainText,normalizeRange} from "../src/features/studio-v2/core/rich-text-engine.ts";
import {resolveLayout} from "../src/features/studio-v2/core/layout-engine.ts";
const style={fontFamily:"sans",fontSize:40,fontWeight:400,italic:false,underline:false,strike:false,color:"#20242B"};
const runs=[{text:"Кыргызстан — салам!",style}];
let formatted=formatRange(runs,{start:0,end:6},{fontWeight:700,color:"#AA0000"});
assert.equal(formatted[0].text,"Кыргыз");
assert.equal(formatted[0].style.fontWeight,700);
assert.equal(formatted[1].style.fontWeight,400);
assert.equal(plainText(formatted),plainText(runs));
let replacement=replaceRange(formatted,{start:6,end:10}," тили");
assert.equal(plainText(replacement),"Кыргыз тили — салам!");
assert.equal(plainText(reconcileText(formatted,"Кыргызстан — салам! Өңүң")),"Кыргызстан — салам! Өңүң");
let mixed=[{text:"А😀",style},{text:"Б",style:{...style,fontWeight:700}}];
assert.deepEqual(normalizeRange(plainText(mixed),{start:2,end:3}),{start:1,end:3});
assert.equal(plainText(replaceRange(mixed,{start:2,end:3},"Ө")),"АӨБ");
assert.equal(plainText(reconcileText(mixed,"А😁Б")),"А😁Б");
assert.equal(sanitizePlainText("abc\r\n\x00def"),"abc\ndef");
assert.equal(plainText(normalizeRuns([{text:"а",style},{text:"б",style}],style)),"аб");
const fresh=createEmptyProjectV2("rich-text-tests");
const node={id:"text-a",type:"text",parentId:"frame-1",x:10,y:20,width:300,height:80,rotation:0,opacity:1,visible:true,locked:false,runs,textAlign:"left",bindingKey:null,autoHeight:true,lineHeight:1.2,letterSpacing:2};
let doc=applyStudioCommand(fresh,{kind:"insertNode",parentId:"frame-1",node});
assert.equal(resolveLayout(doc,{"text-a":150})["text-a"].height,150);
doc=applyStudioCommand(doc,{kind:"updateNode",id:"frame-1",changes:{layout:"vertical",sizing:{width:"fixed",height:"hug"}}});
assert.equal(resolveLayout(doc,{"text-a":150})["frame-1"].height,150);
let session=createEditorSession(doc);
session=beginStudioTransaction(session,"edit text");
session=dispatchStudioCommand(session,{kind:"updateNode",id:node.id,changes:{runs:formatted}});
session=dispatchStudioCommand(session,{kind:"updateNode",id:node.id,changes:{runs:replacement}});
session=commitStudioTransaction(session);
assert.equal(session.undoStack.length,1);
assert.deepEqual(parseProjectV2(JSON.parse(JSON.stringify(session.document))).nodes[node.id].runs,replacement);
session=undoStudio(session);assert.deepEqual(session.document.nodes[node.id].runs,runs);
session=redoStudio(session);assert.deepEqual(session.document.nodes[node.id].runs,replacement);
session=beginStudioTransaction(session,"cancel");session=dispatchStudioCommand(session,{kind:"updateNode",id:node.id,changes:{runs}});session=cancelStudioTransaction(session);assert.deepEqual(session.document.nodes[node.id].runs,replacement);
console.log("PASS: structured rich text ranges, Cyrillic, surrogate pairs, plain paste, measured layout, serialization and history");
