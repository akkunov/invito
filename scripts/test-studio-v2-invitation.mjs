import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,createEditorSession,dispatchStudioCommand,undoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {createWidget,bindDocument,countdownParts,countdownTarget,locationAddress,mapUrl,submitGuestResponse,validateRsvp,bindingText} from "../src/features/studio-v2/core/invitation-behavior.ts";
import {musicSourceSchema,invitationBlockSchema,instantSchema} from "../src/features/studio-v2/core/invitation.schema.ts";
import {responsiveDocument} from "../src/features/studio-v2/core/responsive-engine.ts";
let doc=createEmptyProjectV2("invitation-test","ky");
const put=(key,type,value)=>{doc=applyStudioCommand(doc,{kind:"putVariable",key,variable:{type,label:{ru:key,ky:key}},value:{type,value}});};
put("event.names","text",{ru:"Алина и Тимур",ky:"Алина жана Тимур"});
put("event.date","date","2027-06-14T16:00:00+06:00");
put("event.guests","number",120);
put("event.open","boolean",true);
const text={id:"title",type:"text",parentId:"frame-1",x:0,y:0,width:900,height:80,rotation:0,opacity:1,visible:true,locked:false,runs:[{text:"fallback",style:{fontFamily:"sans",fontSize:40,fontWeight:400,italic:false,underline:false,strike:false,color:"#20242B"}}],textAlign:"center",bindingKey:"event.names"};
doc=applyStudioCommand(doc,{kind:"insertNode",parentId:"frame-1",node:text});
assert.equal(bindDocument(doc).nodes.title.runs[0].text,"Алина жана Тимур");
assert.equal(bindDocument({...doc,locale:"ru"}).nodes.title.runs[0].text,"Алина и Тимур");
assert.equal(doc.nodes.title.runs[0].text,"fallback");
assert.equal(bindingText(doc.values["event.open"],"ky"),"Ооба");
assert.throws(()=>applyStudioCommand(doc,{kind:"setVariableValue",key:"event.date",value:{type:"text",value:{ru:"a",ky:"b"}}}));
assert.equal(instantSchema.safeParse("2027-06-14T16:00:00").success,false);
for(const kind of ["rsvp","countdown","location","gallery","music","schedule"]){
 const widget=createWidget(kind,"widget-"+kind,"frame-1",900,Date.parse("2027-05-01T00:00:00Z"));
 doc=applyStudioCommand(doc,{kind:"insertNode",parentId:"frame-1",node:widget});
 assert.equal(responsiveDocument(doc,"mobile").nodes[widget.id].type,"widget");
}
let countdown=doc.nodes["widget-countdown"].block;
doc=applyStudioCommand(doc,{kind:"updateNode",id:"widget-countdown",changes:{block:{...countdown,targetKey:"event.date"}}});
assert.equal(countdownTarget(doc,doc.nodes["widget-countdown"].block),"2027-06-14T16:00:00+06:00");
assert.throws(()=>applyStudioCommand(doc,{kind:"updateNode",id:"widget-countdown",changes:{block:{...countdown,targetKey:"event.names"}}}));
assert.deepEqual(countdownParts("2027-06-14T16:00:00+06:00",Date.parse("2027-06-13T06:57:56Z")),{days:1,hours:3,minutes:2,seconds:4});
assert.deepEqual(countdownParts("2027-06-14T16:00:00+06:00",Date.parse("2027-06-15T00:00:00Z")),{days:0,hours:0,minutes:0,seconds:0});
assert.ok(mapUrl("Ош & Бишкек").startsWith("https://www.google.com/maps/search/?api=1&query="));
assert.ok(mapUrl("x&y").includes("x%26y"));
assert.equal(locationAddress(doc,{...doc.nodes["widget-location"].block,addressKey:"event.names"}),"Алина жана Тимур");
assert.equal(musicSourceSchema.safeParse("javascript:alert(1)").success,false);
assert.equal(musicSourceSchema.safeParse("https://example.com/song.mp3").success,true);
assert.equal(musicSourceSchema.safeParse("https://user:pass@example.com/song.mp3").success,false);
assert.equal(invitationBlockSchema.safeParse({...doc.nodes["widget-gallery"].block,assetIds:["a","b","c","d","e"]}).success,false);
assert.throws(()=>applyStudioCommand(doc,{kind:"updateNode",id:"widget-gallery",changes:{block:{...doc.nodes["widget-gallery"].block,assetIds:["missing"]}}}));
const yes={name:"  Айгүл  ",attendance:"yes",guests:2};
assert.equal(validateRsvp(yes,2).name,"Айгүл");
assert.throws(()=>validateRsvp(yes,1));
assert.throws(()=>validateRsvp({name:"",attendance:"yes",guests:1},2));
assert.equal(validateRsvp({name:"Айгүл",attendance:"no",guests:0},2).guests,0);
assert.equal(await submitGuestResponse({mode:"preview"},"widget-rsvp",yes,2,null),"preview");
await assert.rejects(()=>submitGuestResponse({mode:"studio"},"widget-rsvp",yes,2,null));
await assert.rejects(()=>submitGuestResponse({mode:"live"},"widget-rsvp",yes,2,null));
await assert.rejects(()=>submitGuestResponse({mode:"preview"},"widget-rsvp",yes,2,"2027-01-01T00:00:00Z",Date.parse("2027-01-02T00:00:00Z")));
let calls=0;
assert.equal(await submitGuestResponse({mode:"live",submitRsvp:async(id,input)=>{calls++;assert.equal(id,"widget-rsvp");assert.equal(input.name,"Айгүл");}},"widget-rsvp",yes,2,null),"sent");
assert.equal(calls,1);
let session=createEditorSession(doc);
session=dispatchStudioCommand(session,{kind:"setVariableValue",key:"event.names",value:{type:"text",value:{ru:"Новые имена",ky:"Жаңы аттар"}}});
assert.equal(bindDocument(session.document).nodes.title.runs[0].text,"Жаңы аттар");
assert.equal(bindDocument(undoStudio(session).document).nodes.title.runs[0].text,"Алина жана Тимур");
assert.deepEqual(parseProjectV2(JSON.parse(JSON.stringify(doc))),doc);
console.log("PASS: typed values, RU/KY bindings, widgets, countdown, media references, safe RSVP preview and live transport");
