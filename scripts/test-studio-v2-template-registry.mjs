import assert from "node:assert/strict";
import {createEmptyProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {createTemplate,appendTemplateVersion,restoreTemplateVersion,duplicateTemplate,filterTemplates,updateTemplateMeta,templateDocument,templateRecordSchema,forkTemplateDocument} from "../src/features/studio-v2/core/template-registry.ts";
const time="2026-11-18T06:30:00.000Z";
const source=createEmptyProjectV2("source");
const meta={name:"Riviera",category:"wedding",description:"Editorial invitation",tags:["minimal"],coverPageId:"page-1",status:"draft"};
let t=createTemplate("template-a",meta,source,time);
assert.equal(t.versions.length,1);
assert.equal(templateDocument(t).id,"template-a");
assert.equal(source.id,"source");
const changed=structuredClone(source);changed.nodes["frame-1"].background="#CCAA88";
t=appendTemplateVersion(t,changed,"New color",time);
assert.equal(t.versions[0].document.nodes["frame-1"].background,"#FFFFFF");
assert.equal(templateDocument(t).nodes["frame-1"].background,"#CCAA88");
changed.nodes["frame-1"].background="#000000";assert.equal(templateDocument(t).nodes["frame-1"].background,"#CCAA88");
t=restoreTemplateVersion(t,1,time);
assert.equal(t.versions.length,3);
assert.equal(templateDocument(t).nodes["frame-1"].background,"#FFFFFF");
assert.equal(t.versions[1].document.nodes["frame-1"].background,"#CCAA88");
const copy=duplicateTemplate(t,"template-b",time);
assert.equal(copy.versions.length,1);assert.equal(copy.meta.status,"draft");assert.equal(templateDocument(copy).id,"template-b");
const ready=updateTemplateMeta(t,{...t.meta,status:"ready"},time);
assert.equal(filterTemplates([copy,ready],"MINIMAL","wedding","ready")[0].id,t.id);
assert.equal(filterTemplates([copy,ready],"","birthday","").length,0);
assert.equal(forkTemplateDocument(templateDocument(t),"project-one").id,"project-one");
assert.throws(()=>createTemplate("bad",{...meta,coverPageId:"missing"},source,time));
assert.throws(()=>restoreTemplateVersion(t,99,time));
assert.throws(()=>templateRecordSchema.parse({...t,versions:[{...t.versions[0],number:9}]}));
assert.deepEqual(templateRecordSchema.parse(JSON.parse(JSON.stringify(t))),t);
console.log("PASS: template registry, snapshots, restore, duplicate, filters, cover integrity and workspace isolation");
