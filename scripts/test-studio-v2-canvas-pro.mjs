import assert from "node:assert/strict";
import {createEmptyProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,applyStudioBatch,createEditorSession,dispatchStudioCommand,undoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {layoutDocument} from "../src/features/studio-v2/core/layout-engine.ts";
import {nodeBounds,nodeCorners,selectionBounds,snapMove} from "../src/features/studio-v2/core/selection-transform.ts";
import {alignSelection,distributeSelection,scaleSelection,rotateSelection,copySelection,pasteSelection,reparentPreserveWorld,distanceGuides,canResizeSelection} from "../src/features/studio-v2/core/canvas-pro.ts";
let doc=createEmptyProjectV2("canvas-pro");
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-7,`${a} != ${b}`);
const shape=(id,x,y,width=100,height=80,parentId="frame-1")=>({id,type:"shape",parentId,x,y,width,height,rotation:0,opacity:1,visible:true,locked:false,shape:"rectangle",fill:"#FF0000",stroke:null,strokeWidth:0});
const add=(d,node)=>applyStudioCommand(d,{kind:"insertNode",parentId:node.parentId,node});
doc=add(add(add(doc,shape("a",20,30)),shape("b",200,90,80)),shape("c",490,200,160));
let aligned=applyStudioCommand(doc,alignSelection(doc,["a","b","c"],"top"));
for(const id of ["a","b","c"])close(nodeBounds(aligned,id).y,30);
let spread=applyStudioCommand(doc,distributeSelection(doc,["a","b","c"],"x"));
close(nodeBounds(spread,"b").x-nodeBounds(spread,"a").x-100,nodeBounds(spread,"c").x-nodeBounds(spread,"b").x-80);
assert.ok(canResizeSelection(doc,["a","b"]));
const bounds=selectionBounds(doc,["a","b"]),scaled=applyStudioBatch(doc,scaleSelection(doc,["a","b"],"se",{x:bounds.width,y:bounds.height}));
close(scaled.nodes.a.width,200);close(scaled.nodes.b.width,160);close(selectionBounds(scaled,["a","b"]).x,bounds.x);
const turned=applyStudioBatch(doc,rotateSelection(doc,["a","b"],90));close(turned.nodes.a.rotation,90);close(turned.nodes.b.rotation,90);
const root=doc.nodes["frame-1"];
doc=add(doc,{...root,id:"nested",parentId:"frame-1",x:500,y:500,width:200,height:250,rotation:37,children:[]});
doc=add(doc,shape("child",50,60,100,80,"nested"));
let moved=applyStudioBatch(doc,reparentPreserveWorld(doc,"a","nested"));
nodeCorners(doc,"a").forEach((p,i)=>{const q=nodeCorners(moved,"a")[i];close(p.x,q.x);close(p.y,q.y);});
assert.throws(()=>reparentPreserveWorld(doc,"nested","nested"));
doc=applyStudioCommand(doc,{kind:"setResponsiveOverride",id:"child",device:"mobile",patch:{x:18}});
const clip=copySelection(doc,layoutDocument(doc),["nested","child"]);
assert.deepEqual(clip.roots,["nested"]);assert.equal(Object.keys(clip.nodes).length,2);
doc=applyStudioCommand(doc,{kind:"createPage",page:{id:"page-two",name:"Вторая",rootNodeId:"frame-two",placement:{x:2400,y:0}},root:{...root,id:"frame-two",children:[]}});
let i=0;const pasted=pasteSelection(doc,clip,"frame-two",()=>"copy-"+(++i));
let session=createEditorSession(doc);session=dispatchStudioCommand(session,pasted.command);
const copy=session.document.nodes[pasted.ids[0]];
close(copy.x,524);close(copy.y,524);
assert.equal(copy.children.length,1);assert.equal(session.document.responsiveOverrides.mobile[copy.children[0]].x,18);
assert.equal(session.undoStack.length,1);assert.deepEqual(undoStudio(session).document.nodes,doc.nodes);
assert.throws(()=>pasteSelection(doc,clip,"frame-two",()=>"same"));
assert.throws(()=>pasteSelection({...doc,id:"another-project"},clip,"frame-two",()=>"new"));
const marks=distanceGuides(doc,["a"],"b");assert.equal(marks.find(m=>m.axis==="x").distance,80);
assert.equal(distanceGuides(doc,["a"],"a").length,0);
assert.equal(doc.nodes.a.x,20);
const guided=applyStudioCommand(doc,{kind:"setGuides",guides:[{id:"guide-a",axis:"x",position:1000}]});
const snap=snapMove(guided,["a"],{x:877,y:0},1,6);close(snap.delta.x,880);close(snap.guideX,1000);
assert.throws(()=>applyStudioCommand(guided,{kind:"setGuides",guides:[{id:"guide-a",axis:"x",position:1000001}]}));
console.log("PASS: alignment, equal gaps, uniform resize, group rotation, reparent, clipboard copy, page coordinates, overrides, undo, distance");
