import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,createEditorSession,dispatchStudioCommand,undoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {resolveLayout,layoutDocument} from "../src/features/studio-v2/core/layout-engine.ts";
const fresh=createEmptyProjectV2("layout-tests");
const shape=(id,x=0,y=0,sizing)=>({id,type:"shape",parentId:"frame-1",x,y,width:100,height:80,rotation:0,opacity:1,visible:true,locked:false,shape:"rectangle",fill:"#FF0000",stroke:null,strokeWidth:0,...(sizing?{sizing}:{})});
const cmd=(doc,id,changes)=>applyStudioCommand(doc,{kind:"updateNode",id,changes});
const add=(doc,node)=>applyStudioCommand(doc,{kind:"insertNode",parentId:node.parentId,node});
let doc=add(add(fresh,shape("a",10,20)),shape("b",200,300));
assert.deepEqual(layoutDocument(doc),doc,"unchanged free-layout geometry");
doc=cmd(doc,"frame-1",{width:400,height:400,layout:"vertical",gap:20,padding:{top:10,right:20,bottom:30,left:40},alignment:"center"});
let g=resolveLayout(doc);
assert.deepEqual(g.a,{x:160,y:10,width:100,height:80});
assert.deepEqual(g.b,{x:160,y:110,width:100,height:80});
doc=cmd(doc,"frame-1",{sizing:{width:"fixed",height:"hug"}});
assert.equal(resolveLayout(doc)["frame-1"].height,220);
const before=JSON.stringify(doc);resolveLayout(doc);assert.equal(JSON.stringify(doc),before);
const free=cmd(doc,"frame-1",{layout:"free"});
assert.equal(free.nodes["frame-1"].height,220);
assert.equal(free.nodes.b.y,110);
doc=cmd(doc,"frame-1",{layout:"horizontal",width:400,height:300,sizing:{width:"fixed",height:"fixed"},gap:20,padding:{top:10,right:10,bottom:10,left:10}});
doc=cmd(doc,"a",{sizing:{width:"fill",height:"fill",maxWidth:120}});
doc=cmd(doc,"b",{sizing:{width:"fill",height:"fixed"}});
g=resolveLayout(doc);assert.equal(g.a.width,120);assert.equal(g.b.width,240);assert.equal(g.a.height,280);
doc=cmd(doc,"b",{visible:false});assert.equal(resolveLayout(doc).b,undefined);
let anchor=add(fresh,shape("a",50,80));
anchor=cmd(anchor,"a",{anchors:{x:"end",y:"stretch"}});
anchor=cmd(anchor,"frame-1",{width:1180,height:2020});
assert.equal(resolveLayout(anchor).a.x,150);assert.equal(resolveLayout(anchor).a.height,180);
const nested={...fresh.nodes["frame-1"],id:"inner",parentId:"frame-1",children:[],layout:"vertical",width:200,height:200,padding:{top:5,right:5,bottom:5,left:5},gap:10,sizing:{width:"fixed",height:"hug"}};
let tree=add(add(fresh,nested),{...shape("child"),parentId:"inner"});
assert.equal(resolveLayout(tree).inner.height,90);
tree=applyStudioCommand(tree,{kind:"reparentNode",id:"child",parentId:"frame-1"});
assert.equal(resolveLayout(tree).inner.height,10);
const invalid=structuredClone(doc);invalid.nodes.a.sizing.minWidth=200;assert.throws(()=>parseProjectV2(invalid));
let session=createEditorSession(anchor);session=dispatchStudioCommand(session,{kind:"updateNode",id:"frame-1",changes:{width:1280}});assert.equal(resolveLayout(session.document).a.x,250);assert.equal(resolveLayout(undoStudio(session).document).a.x,150);
console.log("PASS: layout fixed/fill/hug, nested reflow, limits, anchors, hidden children, compatibility and undo");
