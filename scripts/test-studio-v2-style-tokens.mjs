import assert from "node:assert/strict";
import {createEmptyProjectV2,parseProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,applyStudioBatch,createEditorSession,dispatchStudioCommand,undoStudio,redoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {defaultToken,resolveStyleDocument,styleUsage} from "../src/features/studio-v2/core/style-tokens.ts";
import {snapshotVariant,instantiateComponent} from "../src/features/studio-v2/core/component-engine.ts";
import {appearanceCss} from "../src/features/studio-v2/core/appearance.ts";
import {responsiveDocument} from "../src/features/studio-v2/core/responsive-engine.ts";
let doc=createEmptyProjectV2("styles-test");
const run={text:"Алина жана Тимур",style:{fontFamily:"sans",fontSize:40,fontWeight:400,italic:false,underline:false,strike:false,color:"#111111"}};
const node={id:"title",type:"text",parentId:"frame-1",x:0,y:0,width:900,height:80,rotation:0,opacity:1,visible:true,locked:false,runs:[run],textAlign:"center",bindingKey:null};
const apply=command=>{doc=applyStudioCommand(doc,command);};
apply({kind:"insertNode",parentId:"frame-1",node});
apply({kind:"insertNode",parentId:"frame-1",node:{...node,id:"title2",runs:[{...run,text:"Жаңы текст"}]}});
const color={...defaultToken("primary","Primary","color"),value:"#336699"};
const type={...defaultToken("heading","Heading","typography"),value:{fontFamily:"serif",fontSize:72,fontWeight:600,lineHeight:1.4,letterSpacing:2}};
const gradient=defaultToken("gradient","Gradient","fill");
const stroke=defaultToken("border","Border","stroke");
const effect=defaultToken("shadow","Shadow","effect");
const corners=defaultToken("corners","Corners","corners");
for(const token of [color,type,gradient,stroke,effect,corners])apply({kind:"putStyleToken",token});
for(const id of ["title","title2"]){
 apply({kind:"bindStyle",id,slot:"textColor",tokenId:color.id});
 apply({kind:"bindStyle",id,slot:"typography",tokenId:type.id});
}
for(const [slot,tokenId] of [["fill","gradient"],["stroke","border"],["effect","shadow"],["corners","corners"]])apply({kind:"bindStyle",id:"frame-1",slot,tokenId});
let resolved=resolveStyleDocument(doc);
assert.equal(resolved.nodes.title.runs[0].text,run.text);
assert.equal(resolved.nodes.title2.runs[0].text,"Жаңы текст");
assert.equal(resolved.nodes.title.runs[0].style.color,"#336699");
assert.equal(resolved.nodes.title.runs[0].style.fontSize,72);
assert.equal(resolved.nodes.title.lineHeight,1.4);
assert.equal(doc.nodes.title.runs[0].style.fontSize,40);
assert.ok(appearanceCss(resolved.nodes["frame-1"]).background.startsWith("linear-gradient"));
assert.equal(appearanceCss(resolved.nodes["frame-1"]).borderRadius,"16px 16px 16px 16px");
assert.ok(appearanceCss(resolved.nodes["frame-1"]).outline);
assert.ok(appearanceCss(resolved.nodes["frame-1"]).boxShadow);
assert.throws(()=>applyStudioCommand(doc,{kind:"bindStyle",id:"frame-1",slot:"textColor",tokenId:"primary"}));
assert.throws(()=>applyStudioCommand(doc,{kind:"bindStyle",id:"title",slot:"typography",tokenId:"primary"}));
assert.throws(()=>applyStudioCommand(doc,{kind:"deleteStyleToken",id:"primary"}));
const component={id:"component-title",name:"Title",variants:[snapshotVariant(doc,"title","base","Base")]};
apply({kind:"putComponent",component});
let i=0;doc=applyStudioBatch(doc,instantiateComponent(component,"base","frame-1",()=>"instance-"+(++i)));
assert.equal(doc.nodes["instance-1"].tokenRefs.textColor,"primary");
assert.equal(styleUsage(doc,"primary"),4);
const theme={id:"dark",name:"Dark",overrides:{primary:{...color,value:"#EEDDCC"},heading:{...type,value:{...type.value,fontSize:64}}}};
apply({kind:"putStyleTheme",theme});
let session=createEditorSession(doc);
session=dispatchStudioCommand(session,{kind:"activateStyleTheme",id:"dark"});
resolved=resolveStyleDocument(session.document);
assert.equal(resolved.nodes["instance-1"].runs[0].style.color,"#EEDDCC");
assert.equal(responsiveDocument(resolved,"mobile").nodes.title.runs[0].style.fontSize,64);
assert.equal(resolveStyleDocument(undoStudio(session).document).nodes.title.runs[0].style.color,"#336699");
session=redoStudio(undoStudio(session));
session=dispatchStudioCommand(session,{kind:"bindStyle",id:"instance-1",slot:"textColor",tokenId:null});
assert.equal(session.document.nodes["instance-1"].tokenRefs.textColor,undefined);
assert.equal(session.document.nodes["instance-1"].runs[0].style.color,"#EEDDCC");
session=dispatchStudioCommand(session,{kind:"activateStyleTheme",id:null});
assert.equal(resolveStyleDocument(session.document).nodes["instance-1"].runs[0].style.color,"#EEDDCC");
assert.equal(resolveStyleDocument(session.document).nodes.title.runs[0].style.color,"#336699");
session=dispatchStudioCommand(session,{kind:"putStyleToken",token:{...color,value:"#AA4400"}});
assert.equal(resolveStyleDocument(session.document).nodes.title2.runs[0].style.color,"#AA4400");
assert.equal(session.document.nodes["instance-1"].runs[0].text,run.text);
assert.throws(()=>applyStudioCommand(doc,{kind:"putStyleTheme",theme:{...theme,overrides:{primary:{...type,id:"primary"}}}}));
assert.deepEqual(parseProjectV2(JSON.parse(JSON.stringify(session.document))),session.document);
console.log("PASS: typed shared styles, independent content, theme inheritance, component references, unlink, responsive layout and undo/redo");
