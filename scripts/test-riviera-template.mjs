import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
const read = path => readFileSync(path,"utf8");
const registry = read("src/features/invitations/seed-templates.ts");
assert.match(registry, /rivieraTemplate/);
assert.ok(!registry.includes("birthdayTemplates") && !registry.includes("referenceTemplates"));
const schema = read("src/features/invitations/invitation.schema.ts");
assert.match(schema, /venuePhotoDataUrl/);
assert.match(schema, /\.max\(4\)/);
const hook = read("src/features/invitations/use-invitation-editor.ts");
assert.match(hook,/updateVenuePhoto/);
assert.match(hook,/slice\(0, 4\)/);
const invitation = read("src/components/invitation/riviera-invitation.tsx");
assert.match(invitation, /media\?\.venuePhotoDataUrl \?\? IMAGES\.villa/);
assert.match(invitation, /GalleryBlock/);
const uploader = read("src/components/editor/birthday-gallery-uploader.tsx");
assert.match(uploader, /4\s*-\s*photos\.length/);
assert.match(uploader, /photos\.length < 4/);
assert.ok(existsSync("src/components/editor/riviera-venue-photo-uploader.tsx"));
const layout = read("src/app/[locale]/layout.tsx");
assert.ok(!layout.includes("birthday.css") && !layout.includes("editorial.css"));
for (const file of ["couple","villa","flowers","fabric-left","fabric-right"]) {
  assert.ok(existsSync(`public/images/riviera/${file}.webp`));
}
const art=read("src/components/templates/riviera-template-artwork.tsx");
const css=read("src/app/riviera.css");
assert.match(art, /riviera-card-portrait/);
assert.match(art, /riviera-card-wave/);
assert.match(art, /riviera-card-topbar/);
assert.match(css, /\.riviera-card-portrait::before/);
assert.match(css, /\.riviera-card-preview\s*\{/);
assert.ok(!css.includes(".riviera-card-photo"), "old standalone card style removed");
console.log("PASS: Riviera retained, venue photo editable, gallery max four");
