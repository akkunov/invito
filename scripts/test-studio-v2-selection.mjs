import assert from "node:assert/strict";
import {createEmptyProjectV2} from "../src/features/studio-v2/core/document.schema.ts";
import {applyStudioCommand,applyStudioBatch,createEditorSession,dispatchStudioCommand,beginStudioTransaction,commitStudioTransaction,undoStudio} from "../src/features/studio-v2/core/command-engine.ts";
import {canSelect,normalizeSelection,selectNode,nodeCorners,nodeBounds,moveSelection,resizeNode,rotateNode,marqueeSelection,snapMove,groupSelection,ungroupSelection} from "../src/features/studio-v2/core/selection-transform.ts";
const base=createEmptyProjectV2("selection-tests");
const root=base.nodes["frame-1"];
const shape=(id,x,y,parentId="frame-1")=>({id,type:"shape",parentId,x,y,width:100,height:80,rotation:0,opacity:1,visible:true,locked:false,shape:"rectangle",fill:"#FF0000",stroke:null,strokeWidth:0});
const add=(doc,node)=>applyStudioCommand(doc,{kind:"insertNode",parentId:node.parentId,node});
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-7,`${a} != ${b}`);
const sameCorners=(a,b)=>a.forEach((p,i)=>{close(p.x,b[i].x);close(p.y,b[i].y)});
let doc=add(add(base,shape("a",20,30)),shape("b",200,30));
assert.equal(canSelect(doc,"frame-1"),false);
assert.deepEqual(selectNode(doc,["a"],"b",true),["a","b"]);
assert.deepEqual(selectNode(doc,["a","b"],"a",true),["b"]);
assert.deepEqual(marqueeSelection(doc,"frame-1",{x:0,y:0,width:150,height:130}),["a"]);
assert.equal(canSelect(applyStudioCommand(doc,{kind:"updateNode",id:"a",changes:{locked:true}}),"a"),false);
const original=JSON.stringify(doc);
let sn=snapMove(doc,["a"],{x:77,y:0},1,6);
close(sn.delta.x,80);close(sn.guideX,200);
sn=snapMove(doc,["a"],{x:77,y:0},3,6);
close(sn.delta.x,77);
let next=applyStudioCommand(doc,resizeNode(doc,"a","se",{x:50,y:40},true));
close(next.nodes.a.width,150);close(next.nodes.a.height,120);
sameCorners(nodeCorners(doc,"a").slice(0,1),nodeCorners(next,"a").slice(0,1));
next=applyStudioCommand(doc,rotateNode(doc,"a",450));close(next.nodes.a.rotation,90);
const rotated=next;
next=applyStudioCommand(rotated,resizeNode(rotated,"a","se",{x:-20,y:30}));
sameCorners(nodeCorners(rotated,"a").slice(0,1),nodeCorners(next,"a").slice(0,1));
close(next.nodes.a.width,130);close(next.nodes.a.height,100);
const frame={...root,id:"nested",parentId:"frame-1",x:350,y:100,width:200,height:200,rotation:90,children:[]};
let nested=add(add(doc,frame),shape("child",10,20,"nested"));
assert.deepEqual(normalizeSelection(nested,["nested","child"]),["nested"]);
const moved=applyStudioCommand(nested,moveSelection(nested,["child"],{x:15,y:20}));
const p=nodeCorners(nested,"child")[0],q=nodeCorners(moved,"child")[0];close(q.x-p.x,15);close(q.y-p.y,20);
nested=applyStudioCommand(nested,{kind:"updateNode",id:"nested",changes:{visible:false}});
assert.equal(canSelect(nested,"child"),false);
const grouped=applyStudioBatch(rotated,groupSelection(rotated,["a","b"],"group"));
assert.equal(grouped.nodes.group.background,"transparent");
sameCorners(nodeCorners(rotated,"a"),nodeCorners(grouped,"a"));
const turned=applyStudioCommand(grouped,rotateNode(grouped,"group",33));
const ungrouped=applyStudioBatch(turned,ungroupSelection(turned,"group"));
sameCorners(nodeCorners(turned,"a"),nodeCorners(ungrouped,"a"));
assert.deepEqual(ungrouped.nodes["frame-1"].children,["a","b"]);
assert.equal(JSON.stringify(doc),original);
let session=createEditorSession(doc);
session=beginStudioTransaction(session,"move");
session=dispatchStudioCommand(session,moveSelection(doc,["a","b"],{x:10,y:20}));
session=dispatchStudioCommand(session,moveSelection(doc,["a","b"],{x:50,y:70}));
session=commitStudioTransaction(session);
assert.equal(session.undoStack.length,1);
assert.equal(undoStudio(session).document.nodes.a.x,20);
console.log("PASS Studio v2 selection: marquee, bounds, locked ancestors, rotated resize, zoom snap, group/ungroup, one undo");
